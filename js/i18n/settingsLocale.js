// Sorted keys by length descending to prevent sub-string collision during replacement
const SORTED_PHRASES = Object.keys(SETTINGS_PHRASES).sort((a, b) => b.length - a.length);

/**
 * Transforms an HTML template of Settings view into English if locale is 'en'.
 * Preserves exact structure, event targets, IDs, and classes.
 * @param {string} html 
 * @param {string} locale 
 * @returns {string}
 */
export function localizeSettingsHtml(html, locale = 'id') {
  if (locale !== 'en' || !html) return html;

  let result = html;
  for (const phrase of SORTED_PHRASES) {
    const enPhrase = SETTINGS_PHRASES[phrase];
    if (phrase !== enPhrase && result.includes(phrase)) {
      result = result.replaceAll(phrase, enPhrase);
    }
  }

  // Localize numeric labels and common patterns
  result = result.replace(/(\d+)\s+lagu/g, '$1 tracks');
  result = result.replace(/(\d+)\s+album/g, '$1 albums');
  result = result.replace(/(\d+)\s+putar/g, '$1 plays');
  result = result.replace(/(\d+)\s+putaran/g, '$1 plays');
  result = result.replace(/oleh\s+/g, 'by ');
  result = result.replace(/(\d+)\s+Aktif/g, '$1 Active');
  result = result.replace(/(\d+)\s+Nonaktif/g, '$1 Inactive');
  result = result.replace(/(\d+)\s+Berkas/g, '$1 Files');
  result = result.replace(/(\d+)\s+Dihapus/g, '$1 Removed');

  return result;
}

/**
 * Localizes a single settings text or toast message.
 * @param {string} text 
 * @param {string} locale 
 * @returns {string}
 */
export function localizeSettingsText(text, locale = 'id') {
  if (locale !== 'en' || !text) return text;
  if (SETTINGS_PHRASES[text]) return SETTINGS_PHRASES[text];

  // If not direct match, run phrase replacement for dynamic template literals
  let result = String(text);
  for (const phrase of SORTED_PHRASES) {
    const enPhrase = SETTINGS_PHRASES[phrase];
    if (phrase !== enPhrase && result.includes(phrase)) {
      result = result.replaceAll(phrase, enPhrase);
    }
  }

  result = result.replace(/(\d+)\s+lagu/g, '$1 tracks');
  result = result.replace(/(\d+)\s+album/g, '$1 albums');
  result = result.replace(/(\d+)\s+berkas/g, '$1 files');
  result = result.replace(/(\d+)\s+pintasan/g, '$1 shortcuts');
  result = result.replace(/oleh\s+/g, 'by ');
  return result;
}
